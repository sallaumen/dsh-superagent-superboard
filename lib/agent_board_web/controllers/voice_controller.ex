defmodule AgentBoardWeb.VoiceController do
  @moduledoc """
  The voice API: the ElevenLabs status, text to speech and transcription.

  The browser speaks what `AgentBoard.Voice` writes through the Web Speech
  API; these endpoints are the server-side voice, generated by
  `AgentBoard.ElevenLabs`. The key never leaves the server: the endpoints
  answer with audio or a transcript, never with the key.
  """

  use AgentBoardWeb, :controller

  alias AgentBoard.{Actions, ElevenLabs}
  alias AgentBoard.ElevenLabs.{SpeechCache, Usage}
  alias AgentBoard.Voice
  alias AgentBoard.Voice.{Activity, Phrases}

  # A dictated task title is seconds of audio, not a podcast: the cap keeps a
  # stray upload from reaching ElevenLabs. Overridable for tests.
  @max_audio_bytes 10_000_000

  @doc "GET /api/voice/status -- what is configured, without the key."
  def status(conn, _params) do
    json(
      conn,
      %{
        configured: ElevenLabs.configured?(),
        status: ElevenLabs.status(),
        voice_id: ElevenLabs.voice_id(),
        voice_source: ElevenLabs.voice_source(),
        tts_model: ElevenLabs.tts_model(),
        tts_source: ElevenLabs.tts_source(),
        stt_model: ElevenLabs.stt_model(),
        speak_events: Voice.narrate?(),
        usage: Usage.today(),
        daily_char_cap: Usage.cap()
      }
      |> Map.merge(voice_prefs())
    )
  end

  @doc "GET /api/voice/voices -- the account's voices, for the picker."
  def voices(conn, _params) do
    case ElevenLabs.voices() do
      {:ok, voices} -> json(conn, %{voices: voices})
      {:error, reason} -> voice_error(conn, reason)
    end
  end

  @doc """
  PUT /api/voice/settings -- stores the voice settings.

  Accepts any combination of `voice_id`, `tts_model`, `speak_events`,
  `volume`, `speed`, `style`, `pause` and `attention`; the language is not a
  setting (the voice follows the interface language of the tab). A blank
  `voice_id` clears the pick (back to the default); `tts_model`, when present,
  must be one of the offered models; `speak_events` saves `voice_narrate`.
  """
  def update(conn, params) do
    with :ok <- put_voice(params),
         :ok <- put_model(params),
         :ok <- put_speak_events(params),
         :ok <- put_pref(params, "volume", & &1),
         :ok <- put_pref(params, "speed", & &1),
         :ok <- put_pref(params, "style", & &1),
         :ok <- put_pref(params, "pause", & &1),
         :ok <- put_pref(params, "attention", &(&1 in [true, "true", "1"])) do
      json(
        conn,
        Map.merge(
          %{
            voice_id: ElevenLabs.voice_id(),
            voice_source: ElevenLabs.voice_source(),
            tts_model: ElevenLabs.tts_model(),
            tts_source: ElevenLabs.tts_source(),
            speak_events: Voice.narrate?()
          },
          voice_prefs()
        )
      )
    else
      {:error, reason} -> voice_error(conn, reason)
    end
  end

  defp voice_prefs do
    %{
      volume: Voice.volume(),
      attention: Voice.attention?(),
      speed: Voice.speed(),
      style: Voice.style(),
      pause: Voice.pause()
    }
  end

  # Key by key, like the voice and the model: a refused value answers 400
  # and names itself; an absent key leaves its setting alone. Every save is
  # a yellow action of the registry (`AgentBoard.Actions`), by the API.
  defp put_pref(params, key, value_of) do
    case Map.fetch(params, key) do
      {:ok, value} when is_binary(value) or is_number(value) or is_boolean(value) ->
        save(key, value_of.(value))

      {:ok, _other_shape} ->
        {:error, :invalid_setting}

      :error ->
        :ok
    end
  end

  defp save(setting, value),
    do: Actions.run(:change_setting, %{setting: setting, value: value}, Actions.owner(:api))

  # The API knows no name: a stale one from an earlier pick is cleared.
  defp put_voice(%{"voice_id" => voice_id}) when is_binary(voice_id),
    do: save("voice", {voice_id, nil})

  defp put_voice(_params), do: :ok

  defp put_model(%{"tts_model" => model}) when is_binary(model) do
    if ElevenLabs.valid_tts_model?(String.trim(model)) do
      save("tts_model", model)
    else
      {:error, :invalid_model}
    end
  end

  defp put_model(_params), do: :ok

  # The narration of the rest of the board; off unless asked (it costs voice).
  defp put_speak_events(%{"speak_events" => value}),
    do: save("narrate", value in [true, "true", "1"])

  defp put_speak_events(_params), do: :ok

  @doc "GET /api/voice/speech?text=... -- the spoken audio (mp3)."
  def speech(conn, params), do: speak(conn, params)

  @doc "POST /api/voice/speech -- the spoken audio (mp3)."
  def speech_post(conn, params), do: speak(conn, params)

  @doc """
  GET /api/voice/stream?text=... -- the spoken audio, streamed as it is
  generated (the browser starts playing in about half a second instead of
  waiting for the whole file). A text already spoken with the same voice and
  settings comes from `SpeechCache` at once. A failure before the first byte
  is a JSON error like `speech/2`; one in the middle ends the stream.
  """
  def stream(conn, params) do
    case speech_params(params) do
      {:ok, text, voice, language} -> stream_cached(conn, text, speech_opts(voice, language))
      {:error, reason} -> voice_error(conn, reason)
    end
  end

  defp stream_cached(conn, text, opts) do
    key = SpeechCache.key(text, opts)

    case SpeechCache.get(key) do
      {:ok, audio} ->
        Usage.record_tts(0, :cache)

        Activity.record(:tts, :ok, "voice from the cache (#{String.length(text)} characters)",
          ms: 0
        )

        conn
        |> put_resp_content_type("audio/mpeg", nil)
        |> put_resp_header("x-voice-cache", "hit")
        |> send_resp(200, audio)

      :miss ->
        stream_or_follow(conn, text, opts, key)
    end
  end

  # WebKit asks for the same audio twice at once; the second request waits
  # for the first instead of paying ElevenLabs again.
  defp stream_or_follow(conn, text, opts, key) do
    case SpeechCache.claim(key) do
      :leader ->
        try do
          {conn, audio} = stream_fresh(conn, text, opts, key)
          SpeechCache.release(key, audio)
          conn
        after
          # A crash midway leaves no claim behind; after a release this is a no-op.
          SpeechCache.release(key, nil)
        end

      :follower ->
        case SpeechCache.await(key, 10_000) do
          {:ok, audio} ->
            Usage.record_tts(0, :cache)
            Activity.record(:tts, :ok, "same voice reused from a simultaneous request", ms: 0)

            conn
            |> put_resp_content_type("audio/mpeg", nil)
            |> put_resp_header("x-voice-cache", "inflight")
            |> send_resp(200, audio)

          _gone_or_timeout ->
            {conn, _audio} = stream_fresh(conn, text, opts, key)
            conn
        end
    end
  end

  # The conn and the audio so far live in this request process's dictionary
  # while Req calls back with each chunk; both are read back right after.
  # Answers the conn and the whole audio, or nil when there is none to keep.
  defp stream_fresh(conn, text, opts, key) do
    Process.put(:voice_stream, {conn, []})
    started = System.monotonic_time(:millisecond)

    on_chunk = fn data ->
      {conn, audio} = Process.get(:voice_stream)

      conn =
        if conn.state == :chunked do
          conn
        else
          Activity.record(:tts, :info, "first sound on its way",
            ms: System.monotonic_time(:millisecond) - started
          )

          conn |> put_resp_content_type("audio/mpeg", nil) |> send_chunked(200)
        end

      case chunk(conn, data) do
        {:ok, conn} ->
          Process.put(:voice_stream, {conn, [audio | data]})
          :ok

        {:error, _closed} ->
          Process.put(:voice_stream, {conn, :abandoned})
          :halt
      end
    end

    result = ElevenLabs.speech_stream(text, opts, on_chunk)
    {conn, audio} = Process.delete(:voice_stream)
    ms = System.monotonic_time(:millisecond) - started
    finish_stream(conn, result, audio, text, key, ms)
  end

  defp finish_stream(%{state: :chunked} = conn, :ok, audio, text, key, ms) when is_list(audio) do
    audio = IO.iodata_to_binary(audio)
    SpeechCache.put(key, text, audio)
    Activity.record(:tts, :ok, "voice generated (#{String.length(text)} characters)", ms: ms)
    {conn, audio}
  end

  defp finish_stream(%{state: :chunked} = conn, :ok, :abandoned, _text, _key, ms) do
    Activity.record(:tts, :info, "the browser stopped listening midway", ms: ms)
    {conn, nil}
  end

  defp finish_stream(%{state: :chunked} = conn, {:error, reason}, _audio, _text, _key, ms) do
    Activity.record(:tts, :error, "the voice stopped midway", ms: ms, reason: reason)
    {conn, nil}
  end

  defp finish_stream(conn, {:error, reason}, _audio, _text, _key, ms) do
    Activity.record(:tts, :error, "the voice was not generated", ms: ms, reason: reason)
    {voice_error(conn, reason), nil}
  end

  defp finish_stream(conn, _result, _audio, _text, _key, ms) do
    Activity.record(:tts, :error, "ElevenLabs sent no audio", ms: ms)
    {voice_error(conn, :empty_audio), nil}
  end

  # The endpoint only ever answers mp3 (the fixed default output format), so
  # the content type is a literal, never derived from the request.
  defp speak(conn, params) do
    with {:ok, text, voice, language} <- speech_params(params),
         {:ok, audio} <- generate(text, voice, language) do
      conn
      |> put_resp_content_type("audio/mpeg", nil)
      |> send_resp(200, audio)
    else
      {:error, reason} -> voice_error(conn, reason)
    end
  end

  # The request is validated before any paid call: a wrong text or voice
  # never reaches ElevenLabs.
  defp speech_params(%{"text" => text} = params) when is_binary(text) and byte_size(text) > 0 do
    voice = if params["voice"] in [nil, ""], do: nil, else: params["voice"]
    language = params["language"]

    cond do
      not ElevenLabs.valid_text?(text) -> {:error, :text_too_long}
      not offered_voice?(voice) -> {:error, :invalid_voice}
      not offered_language?(language) -> {:error, :invalid_language}
      true -> {:ok, text, voice, language}
    end
  end

  defp speech_params(_params), do: {:error, :missing_text}

  # Neither is required: no voice is the saved one, no language sends no
  # hint. A value outside the offer is refused.
  defp offered_voice?(nil), do: true
  defp offered_voice?(voice), do: ElevenLabs.valid_voice_id?(voice)

  defp offered_language?(nil), do: true
  defp offered_language?(language), do: Phrases.valid_language?(language)

  defp generate(text, voice, language) do
    opts = speech_opts(voice, language)
    key = SpeechCache.key(text, opts)

    case SpeechCache.get(key) do
      {:ok, audio} ->
        Usage.record_tts(0, :cache)
        {:ok, audio}

      :miss ->
        with {:ok, %{audio: audio}} <- ElevenLabs.speech(text, opts) do
          SpeechCache.put(key, text, audio)
          {:ok, audio}
        end
    end
  end

  # Every input that changes the audio is explicit here, so the cache key
  # covers the voice, model and language even when they are defaults. The
  # language is the request's (the tab that asks says which it speaks);
  # without one no hint is sent and the model reads it from the text.
  defp speech_opts(voice, language) do
    [
      voice: voice || ElevenLabs.voice_id(),
      model: ElevenLabs.tts_model(),
      language: language && Phrases.tts_code(language),
      speed: Voice.speed(),
      stability: Voice.stability()
    ]
  end

  @doc "POST /api/voice/transcribe -- the audio body transcribed (JSON)."
  def transcribe(conn, params) do
    # The hint is refused before the audio is read: a wrong one costs nothing.
    with {:hint, true} <- {:hint, offered_hint?(params["language"])},
         {:ok, body, conn} <- read_body(conn, length: audio_max_bytes()),
         true <- byte_size(body) > 0 do
      transcribed(conn, body, params)
    else
      {:hint, false} -> voice_error(conn, :invalid_language)
      {:more, _body, _conn} -> voice_error(conn, :audio_too_large)
      _ -> voice_error(conn, :missing_audio)
    end
  end

  # The STT hint is the two-letter code the TTS uses (`pt`, `en`); none is allowed.
  defp offered_hint?(nil), do: true
  defp offered_hint?(language), do: language in Enum.map(Phrases.languages(), & &1.tts)

  defp transcribed(conn, body, params) do
    started = System.monotonic_time(:millisecond)

    case ElevenLabs.transcribe(body, filename_for_content_type(conn),
           language: params["language"]
         ) do
      {:ok, transcript} ->
        record_transcript(transcript, System.monotonic_time(:millisecond) - started)
        json(conn, transcript)

      {:error, reason} ->
        Activity.record(:transcribe, :error, "the transcription failed",
          ms: System.monotonic_time(:millisecond) - started,
          reason: reason
        )

        voice_error(conn, reason)
    end
  end

  defp record_transcript(transcript, ms) do
    case transcript.text |> to_string() |> String.split() |> length() do
      0 -> Activity.record(:transcribe, :info, "no word recognized", ms: ms)
      words -> Activity.record(:transcribe, :ok, "heard #{words} words", ms: ms)
    end
  end

  defp audio_max_bytes do
    Application.get_env(:agent_board, :voice_audio_max_bytes, @max_audio_bytes)
  end

  defp voice_error(conn, reason) do
    {status, message} = status_and_message(reason)
    conn |> put_status(status) |> json(%{error: message})
  end

  defp status_and_message(:not_configured), do: {503, "voice not configured"}
  defp status_and_message(:missing_text), do: {400, "a text is required"}
  defp status_and_message(:empty_audio), do: {502, "ElevenLabs returned no audio"}
  defp status_and_message(:text_too_long), do: {400, "the text is too long for one request"}
  defp status_and_message(:missing_audio), do: {400, "an audio body is required"}
  defp status_and_message(:audio_too_large), do: {413, "the audio is too large"}
  defp status_and_message(:invalid_voice), do: {400, "a valid voice id is required"}
  defp status_and_message(:invalid_model), do: {400, "an offered TTS model is required"}
  defp status_and_message(:invalid_language), do: {400, "an offered voice language is required"}
  defp status_and_message(:invalid_volume), do: {400, "the volume must be 0 to 100"}
  defp status_and_message(:invalid_speed), do: {400, "the speed must be 0.8 to 1.2"}

  defp status_and_message(:invalid_style),
    do: {400, "the style must be steady, natural or expressive"}

  defp status_and_message(:invalid_pause), do: {400, "the pause must be short, normal or long"}
  defp status_and_message(:invalid_setting), do: {400, "a setting must be text or a number"}
  defp status_and_message(:auth_expired), do: {401, "ElevenLabs rejected the key"}
  defp status_and_message(:usage_limit), do: {429, "ElevenLabs usage limit reached"}
  defp status_and_message(:quota_exceeded), do: {402, "ElevenLabs credits are spent"}
  defp status_and_message({:http, status}), do: {502, "ElevenLabs HTTP #{status}"}
  defp status_and_message(other), do: {502, "ElevenLabs error: #{inspect(other)}"}

  # The content type picks the extension; ElevenLabs sniffs the bytes anyway.
  defp filename_for_content_type(conn) do
    case get_req_header(conn, "content-type") |> List.first() do
      nil -> "recording.audio"
      type -> content_type_to_filename(String.split(type, ";") |> List.first())
    end
  end

  defp content_type_to_filename(type) do
    case type do
      "audio/webm" -> "recording.webm"
      "audio/mp4" -> "recording.m4a"
      "audio/mpeg" -> "recording.mp3"
      "audio/wav" -> "recording.wav"
      "audio/x-wav" -> "recording.wav"
      "audio/ogg" -> "recording.ogg"
      "audio/flac" -> "recording.flac"
      _ -> "recording.audio"
    end
  end
end
